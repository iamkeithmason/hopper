-- HOP-20: a shared aesthetic vocabulary, so tags group images instead of scattering them.
-- hopper.aesthetics holds the 29 tags (grouped interface, editorial, illustration, genre, mood).
-- hopper.aesthetic_aliases maps the free-form tags from the first backfill onto them.
-- notes.aesthetics is rewritten to vocabulary tags; the original tags stay in attachments.design_read.

create table hopper.aesthetics (
  name text primary key,
  grp text not null check (grp in ('interface', 'editorial', 'illustration', 'genre', 'mood')),
  description text not null
);

create table hopper.aesthetic_aliases (
  alias text not null,
  name text not null references hopper.aesthetics(name) on update cascade on delete cascade,
  primary key (alias, name)
);

revoke all on hopper.aesthetics, hopper.aesthetic_aliases from public, anon, authenticated;

-- Vocabulary tags for a list of free-form tags: exact vocabulary names pass through, aliases map, the rest drop.
create or replace function hopper.canonical_aesthetics(p_tags text[])
 returns text[]
 language sql
 stable
 set search_path to ''
as $function$
  select coalesce(array_agg(distinct x order by x), '{}') from (
    select a.name x from hopper.aesthetics a where a.name = any(p_tags)
    union
    select al.name from hopper.aesthetic_aliases al where al.alias = any(p_tags)
  ) s
$function$;

